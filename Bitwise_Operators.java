public class Bitwise_Operators{
    public static void main(String[] args){
        // Bit-Wise AND
        System.out.println((5 & 6));

        // Bit-Wise OR
        System.out.println((5 | 6));

        // Bit-Wise XOR
        System.out.println((5 ^ 6));

        // Binary one's complement
        System.out.println((~0));
        System.out.println((~5));
    }
}
