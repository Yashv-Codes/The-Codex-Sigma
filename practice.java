import java.util.*;
public class practice{
    public static void main(String[] args){
        Scanner sc = new Scanner(System.in);
        System.out.print("Enter a no: ");
        int n = sc.nextInt();
        int i = 1;
        int sum = 0;
        while(i <= n){
            sum += i;
            i++;
        }
        System.out.println("Total sum : "+sum);
        sc.close();
        

    }
}






        
        
        
        
        
       


        
         
        
    

